const publicPatterns = Object.entries(PUBLIC_INDONESIAN)
  .filter(([key]) => /\{\w+\}/.test(key))
  .sort(
    ([left], [right]) => right.replace(/\{\w+\}/g, "").length - left.replace(/\{\w+\}/g, "").length,
  )
  .map(([key, translation]) => {
    const names: string[] = [];
    const escaped = key.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const pattern = escaped.replace(/\\\{(\w+)\\\}/g, (_match, name: string) => {
      names.push(name);
      return "(.+?)";
    });
    return { regex: new RegExp(`^${pattern}$`), names, translation };
  });

function publicTime(text: string): string {
  return text.replace(
    /\b(1[0-2]|[1-9]):([0-5]\d) (AM|PM)\b/g,
    (_match, hour: string, minute: string, period: string) => {
      let value = Number(hour) % 12;
      if (period === "PM") {
        value += 12;
      }
      return `${String(value).padStart(2, "0")}.${minute}`;
    },
  );
}

export function translatePublic(
  language: PublicLanguage,
  text: string,
  params: Record<string, string | number> = {},
): string {
  let translated = text;
  let values = params;
  if (language === "id") {
    translated = PUBLIC_INDONESIAN[text] ?? text;
    if (translated === text) {
      for (const pattern of publicPatterns) {
        const match = text.match(pattern.regex);
        if (match) {
          translated = pattern.translation;
          values = { ...params };
          pattern.names.forEach((name, index) => {
            values[name] = match[index + 1];
          });
          break;
        }
      }
    }
    values = { ...values };
    for (const key of ["time", "day"]) {
      if (typeof values[key] === "string") {
        values[key] = publicTime(PUBLIC_INDONESIAN[values[key]] ?? values[key]);
      }
    }
    if (/^(1[0-2]|[1-9]):[0-5]\d (AM|PM)$/.test(translated)) {
      return publicTime(translated);
    }
  }
  return translated.replace(/\{(\w+)\}/g, (match, key: string) => {
    if (Object.prototype.hasOwnProperty.call(values, key)) {
      return String(values[key]);
    }
    return match;
  });
}
